// usage: node ktx2_encode.cjs <encoderDir> <in.rgba> <width> <height> <out.ktx2> <srgb|linear|normal> [quality] [alpha]
const path = require('path')
const fs = require('fs')
const [encDir, input, w, h, output, kind, q, alpha] = process.argv.slice(2)
const BASIS = require(path.resolve(encDir, 'basis_encoder.js'))
;(async () => {
  const M = await BASIS({ locateFile: (f) => path.resolve(encDir, f) })
  M.initializeBasis()
  const enc = new M.BasisEncoder()
  const data = new Uint8Array(fs.readFileSync(input))
  if (!enc.setSliceSourceImage(0, data, Number(w), Number(h), M.ldr_image_type.cRGBA32)) throw new Error('setSliceSourceImage failed')
  enc.setCreateKTX2File(true)
  enc.setKTX2UASTCSupercompression(true)
  enc.setFormatMode(M.basis_tex_format.cETC1S)
  const srgb = kind === 'srgb'
  enc.setKTX2AndBasisSRGBTransferFunc(srgb)
  enc.setPerceptual(srgb)
  enc.setMipSRGB(srgb)
  enc.setMipGen(true)
  if (kind === 'normal') enc.setNormalMapPreset()
  enc.setQualityLevel(Number(q ?? (kind === 'normal' ? 255 : 200)))
  enc.setETC1SCompressionLevel(2)
  enc.setCheckForAlpha(alpha === '1')
  const out = new Uint8Array(1024 * 1024 * 16)
  const n = enc.encode(out)
  if (!n) throw new Error('encode failed')
  fs.writeFileSync(output, out.subarray(0, n))
  enc.delete()
  console.log(path.basename(output), n)
})().catch((e) => {
  console.error('ERR', e && e.message ? e.message : e)
  process.exit(1)
})
